"""Measure LOCAL profile resources and authenticated memory-list latency.

No synthetic numbers, no automatic writes, no destructive operations.
Requires the stack to be started with scripts/launch_local.py and Docker.
Measurements depend on the machine and current dataset, not an SLA.
"""
from __future__ import annotations
import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime, timezone
import json
import math
import os
from pathlib import Path
import platform
import statistics
import subprocess
import time
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
URL = "http://127.0.0.1:8765/v1/memories?limit=10"
UNITS = {"B":1,"kB":1000,"MB":1000**2,"GB":1000**3,"TB":1000**4,
         "KiB":1024,"MiB":1024**2,"GiB":1024**3,"TiB":1024**4}

def parse_bytes(raw: str) -> int:
    import re
    m = re.fullmatch(r"\s*([0-9]+(?:\.[0-9]+)?)\s*([A-Za-z]+)\s*", raw)
    if not m or m[2] not in UNITS:
        raise ValueError(f"Unknown Docker byte unit: {raw!r}")
    return round(float(m[1]) * UNITS[m[2]])

def percentile(values: list[float], q: float) -> float | None:
    if not values:
        return None
    values = sorted(values)
    return round(values[min(len(values)-1, math.ceil(q*len(values))-1)], 3)

def command(args: list[str]) -> str:
    return subprocess.check_output(args, cwd=ROOT, text=True, stderr=subprocess.PIPE).strip()

def compose(profile: str) -> list[str]:
    args = ["docker","compose","--env-file",str(ROOT/".env.local"),
            "-f","compose.yaml","-f","compose.app.yaml"]
    if profile=="full":
        args += ["-f","compose.worker.yaml"]
    return args

def environment() -> dict[str, str]:
    path=ROOT/".env.local"
    if not path.is_file():
        raise RuntimeError("Start with python scripts/launch_local.py up --profile lite")
    result={}
    for line in path.read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.startswith("#"):
            k,v=line.split("=",1)
            result[k]=v
    return result

def container_ids(profile: str) -> dict[str, str]:
    ids={}
    for service in (["memory-db","memory-api"]+(["memory-worker"] if profile=="full" else [])):
        cid=command(compose(profile)+["ps","-q",service])
        if not cid:
            raise RuntimeError(f"Missing running service: {service}")
        ids[service]=cid.splitlines()[0]
    return ids

def sample_stats(ids: dict[str, str]) -> dict[str, dict]:
    # Names are generated by Docker and never supplied by an HTTP request.
    raw=command(["docker","stats","--no-stream","--format","{{json .}}",*ids.values()])
    found={}
    for line in raw.splitlines():
        row=json.loads(line)
        cid=row.get("ID","")
        match=next((name for name,full in ids.items() if full.startswith(cid) or cid.startswith(full)),None)
        if match is None:
            continue
        mem=row["MemUsage"].split("/")[0].strip()
        cpu=float(row["CPUPerc"].rstrip("%"))
        found[match]={"memory_bytes":parse_bytes(mem),"cpu_percent":cpu}
    if len(found)!=len(ids):
        raise RuntimeError("Docker stats unavailable for one or more containers")
    return found

def request_memory(api_key: str) -> tuple[bool,float,str|None]:
    req=Request(URL,headers={"Authorization":"Bearer "+api_key})
    start=time.perf_counter()
    try:
        with urlopen(req,timeout=15) as resp:
            ok=resp.status==200
            # Consume body; this records end-to-end API response time.
            payload=resp.read()
            if ok:
                json.loads(payload)
        return ok, (time.perf_counter()-start)*1000, None if ok else "HTTP_NON_200"
    except Exception as exc:
        return False,(time.perf_counter()-start)*1000,type(exc).__name__

def volume_disk_kib(ids:dict[str,str]) -> dict[str,int|None]:
    result={}
    # Real mounted-volume usage, not an estimate from image layers.
    for service,directory in [("memory-db","/var/lib/postgresql"),("memory-api","/app/data/objects")]:
        try:
            raw=command(["docker","exec",ids[service],"du","-sk",directory])
            result[service]=int(raw.split()[0])
        except (ValueError,IndexError,subprocess.CalledProcessError):
            result[service]=None
    return result

def main() -> int:
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--requests",type=int,default=100)
    parser.add_argument("--concurrency",type=int,default=4)
    parser.add_argument("--output",default="benchmark-results/local-resources.json")
    args=parser.parse_args()
    if not (1<=args.requests<=100000 and 1<=args.concurrency<=200):
        parser.error("requests must be 1..100000 and concurrency 1..200")
    env=environment()
    profile=env.get("MEMORY_LOCAL_PROFILE","lite")
    if profile not in ("lite","standard","full"):
        parser.error("Unknown profile")
    key=env.get("MEMORY_API_KEY","")
    if len(key)<32:
        parser.error("Strong local API key required")
    ids=container_ids(profile)
    before=sample_stats(ids)
    start=time.perf_counter()
    with ThreadPoolExecutor(max_workers=args.concurrency) as pool:
        futures=[pool.submit(request_memory,key) for _ in range(args.requests)]
        results=[f.result() for f in as_completed(futures)]
    elapsed=time.perf_counter()-start
    after=sample_stats(ids)
    durations=[ms for ok,ms,_ in results if ok]
    failures=[err for ok,_,err in results if not ok]
    report={
        "kind":"local-observation-not-production-sla",
        "measured_at_utc":datetime.now(timezone.utc).isoformat(),
        "host":platform.platform(),
        "profile":profile,
        "method":"GET /v1/memories?limit=10 (authenticated, read-only)",
        "requests":args.requests,
        "concurrency":args.concurrency,
        "elapsed_seconds":round(elapsed,3),
        "successes":len(durations),
        "failures":len(failures),
        "failure_types":sorted(set(failures)),
        "latency_ms":{"p50":percentile(durations,.5),"p95":percentile(durations,.95),
                      "p99":percentile(durations,.99)},
        "docker_stats_before":before,
        "docker_stats_after":after,
        "volume_disk_kib":volume_disk_kib(ids),
        "notes":[
            "CPU percentages are instantaneous Docker samples; not time-averaged CPU usage.",
            "Memory samples are container usage, not isolated process RSS or peak RAM.",
            "Disk is mounted DB/object volume usage; excludes container images and Docker metadata.",
            "Read-only browse latency does not measure write, extraction, semantic search or end-to-end agent performance."
        ],
    }
    path=Path(args.output)
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(report,ensure_ascii=False,indent=2))
    return 0 if not failures else 1

if __name__=="__main__":
    raise SystemExit(main())
